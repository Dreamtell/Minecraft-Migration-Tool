# -*- coding: utf-8 -*-
r"""把字符串里的不可见控制字符换成看得见的写法。

为的是什么：路径里混进 0x0B（比如源码里写了反斜杠 + v，被当成转义吃掉了）、
或者配置里带进 bell / 退格 / 换页 / 回车 这类控制字符时，Tk / PIL 都画不出来，
屏幕上就是一个方块，看着像「字符显示异常」。

统一在这里还原成「反斜杠 + 字母」的写法，这样路径还能读得懂；其它没意义的控制符直接去掉。
"""
_BS = chr(92)
_可见转义 = {7: _BS + "a", 8: _BS + "b", 11: _BS + "v", 12: _BS + "f", 13: _BS + "r"}


def 可见(文本):
    """返回可以安全显示的字符串（控制字符已转成文字）。"""
    文 = "" if 文本 is None else str(文本)
    if not 文:
        return 文
    出 = []
    for ch in 文:
        码 = ord(ch)
        if 码 >= 32 and 码 != 127:
            出.append(ch)
        elif 码 in _可见转义:
            出.append(_可见转义[码])
        elif 码 in (9, 10):
            出.append(" ")
    return "".join(出)
